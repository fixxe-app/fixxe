package com.example.currencyconverter.ui

/**
 * Разбор введённой суммы. Одинаковые правила на всех трёх платформах.
 *
 * Десятичный знак на цифровой клавиатуре зависит от региона телефона: в
 * России, Сербии, Германии это запятая. Поэтому запятую нельзя слепо считать
 * разделителем разрядов, даже если в настройках выбран именно он, — иначе
 * «1,5» молча превращается в 15.
 *
 *  - есть и точка, и запятая — десятичный знак тот, что правее («1,234.56»,
 *    «1.234,56»), другой — разряды;
 *  - один знак встречается несколько раз — это разряды («1,234,567»);
 *  - одна запятая — десятичная, кроме случая, когда выбрана группировка
 *    запятой и за ней ровно группы по три цифры («1,500» = 1500);
 *  - пробелы и неразрывные пробелы — всегда разряды.
 */
object AmountParser {
    fun parse(input: String, grouping: Int): Double {
        var t = input.filterNot { it == ' ' || it == '\u00A0' || it == '\u202F' }
        val dot = t.lastIndexOf('.'); val comma = t.lastIndexOf(',')
        t = when {
            dot >= 0 && comma >= 0 ->
                if (comma > dot) t.replace(".", "").replace(',', '.') else t.replace(",", "")
            comma >= 0 -> when {
                t.count { it == ',' } > 1 -> t.replace(",", "")
                grouping == 2 && Regex("""^\d{1,3}(,\d{3})+$""").matches(t) -> t.replace(",", "")
                else -> t.replace(',', '.')
            }
            t.count { it == '.' } > 1 -> t.replace(".", "")
            else -> t
        }
        val v = t.toDoubleOrNull() ?: return 0.0
        return if (v.isFinite()) v else 0.0
    }
}
